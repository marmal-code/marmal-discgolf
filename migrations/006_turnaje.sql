CREATE TABLE IF NOT EXISTS event_discs (
  event_id INT NOT NULL,
  disc_id INT NOT NULL,
  PRIMARY KEY (event_id, disc_id),
  CONSTRAINT fk_ed_event FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS event_todo (
  id INT AUTO_INCREMENT PRIMARY KEY,
  event_id INT NOT NULL,
  text VARCHAR(200) NOT NULL,
  done TINYINT(1) NOT NULL DEFAULT 0,
  sort INT NOT NULL DEFAULT 0,
  CONSTRAINT fk_todo_event FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_czech_ci;
